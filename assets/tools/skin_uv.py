"""Write assets/skin_uv.b64.txt: texture coordinates for the skin, hair and eye groups of assets/players.b64.txt (#207 round 1).
Usage: python3 skin_uv.py <makehuman repo path> <assets folder> [proof folder]
The pack keeps one vertex per position and has no UVs, and MakeHuman's UVs split at seams, so UVs cannot be one per packed
vertex. This file joins to the pack without changing it:
  - `uv`: one UV per packed vertex (u16 pairs, 0 for vertices outside the listed groups) = the UV most of its corners use;
  - `extra`: (vertex, u, v) rows for the other UVs a seam vertex has; `fix`: (corner, extra row) pairs, corner = position in
    the pack's index buffer. A loader appends one copy of `vertex` per extra row (same position, skin and offsets) with that UV
    and points those corners at the copy. Corners not listed use `uv` of their own vertex.
Skin and hair UVs come from MakeHuman's base mesh (CC0, LICENSE.ASSETS.md): the pack's body vertices are, in order, the sorted
vertices of the base.obj `body` group (build_players.py), so each packed triangle is found back in base.obj and takes the vt of
its corners. Eye spheres are generated by build_players.py, so their UVs are generated too: u = longitude, v = latitude.
UVs are stored as in the obj (v up, origin bottom left): a three.js texture loads with flipY true, the default.
Optional proof folder: uv_<group>.png = the UV layout with faces coloured by where they are on the body (eyes, lips, ears, nose)."""
import sys, json, struct, base64, numpy as np

MH, A = sys.argv[1], sys.argv[2]
PROOF = sys.argv[3] if len(sys.argv) > 3 else None
Q = 65535                     # u16 UV quantisation
GROUPS = ('skin', 'hair', 'eyeWhite', 'iris')
EYE_R, EYE_S = 6, 8           # Rings and segments of build_players.py sphere()
EYES_PER_BODY = 4             # Two spheres (white, pupil) per eye

# The pack
raw = base64.b64decode(open(f'{A}/players.b64.txt').read())
assert raw[:4] == b'YDPL'; hl = struct.unpack('<I', raw[4:8])[0]; H = json.loads(raw[8:8 + hl])
n, ni = H['n'], H['ni']; off = 8 + hl
Pq = np.frombuffer(raw, np.uint16, n * 3, off).reshape(n, 3); off += n * 6 * (1 + len(H['kinds']) - 1) + n * 8
idx = np.frombuffer(raw, np.uint16, ni, off).astype(np.int64); assert off + ni * 2 == len(raw)
P = np.array(H['lo']) + Pq * np.array(H['ps'])
grp = {name: (s, c) for s, c, name in H['groups']}

# MakeHuman base mesh
V, VT, F, FT, G, g = [], [], [], [], [], ''
for ln in open(MH + '/makehuman/data/3dobjs/base.obj'):
    if ln.startswith('v '): V.append(0)
    elif ln.startswith('vt '): VT.append([float(x) for x in ln.split()[1:3]])
    elif ln.startswith('g '): g = ln.split()[1]
    elif ln.startswith('f '):
        t = [c.split('/') for c in ln.split()[1:]]; F.append([int(c[0]) - 1 for c in t]); FT.append([int(c[1]) - 1 for c in t]); G.append(g)
VT = np.array(VT)
body = [k for k, gg in enumerate(G) if gg == 'body']
used = sorted({i for k in body for i in F[k]})
nb = len(used); assert nb + EYES_PER_BODY * (EYE_R + 1) * EYE_S == n, (nb, n)
# Triangles exactly as build_players.py cuts them: (0,1,2) and (0,2,3) of each face, in packed vertex ids
remap = {o: k for k, o in enumerate(used)}
tri = {}
for k in body:
    f = [remap[i] for i in F[k]]; ft = FT[k]
    for t in ((0, 1, 2), (0, 2, 3)) if len(f) == 4 else ((0, 1, 2),):
        tri[tuple(f[c] for c in t)] = [VT[ft[c]] for c in t]

def eye_uv(v):
    """Generated eye sphere vertex -> (u, v), and its segment index (for the wrap seam)."""
    k = (v - nb) % ((EYE_R + 1) * EYE_S); i, j = divmod(k, EYE_S); return j, np.array([j / EYE_S, 1 - i / EYE_R])

cornerUV = {}                 # corner -> uv
for name in GROUPS:
    s, c = grp[name]
    for t0 in range(s, s + c, 3):
        tv = tuple(idx[t0:t0 + 3])
        if name in ('eyeWhite', 'iris'):
            js = [eye_uv(v)[0] for v in tv]; uvs = [eye_uv(v)[1].copy() for v in tv]
            for a in range(3):          # Faces across the wrap seam use u = 1 on the segment-0 side
                if js[a] == 0 and max(js) == EYE_S - 1: uvs[a][0] = 1.
        else:
            uvs = tri[tv]
        for a in range(3): cornerUV[t0 + a] = np.asarray(uvs[a])

qz = lambda uv: tuple(int(x) for x in np.floor(np.clip(uv, 0, 1) * Q + .5))
per = {}
for cn, uv in cornerUV.items(): per.setdefault(int(idx[cn]), {}).setdefault(qz(uv), []).append(cn)
UV = np.zeros((n, 2), np.uint16); extra, fix = [], []
for v, d in sorted(per.items()):
    order = sorted(d, key=lambda u: -len(d[u])); UV[v] = order[0]
    for u in order[1:]:
        for cn in d[u]: fix.append((cn, len(extra)))
        extra.append((v, *u))
assert len(extra) < 65536
E = np.array(extra, np.uint16).reshape(-1, 3); X = np.array(sorted(fix), np.uint32).reshape(-1, 2)
hd = {'v': 1, 'pack': 'players.b64.txt', 'n': n, 'ni': ni, 'groups': {k: list(grp[k]) for k in GROUPS}, 'q': Q, 'nExtra': len(E), 'nFix': len(X),
      'layout': 'uv u16[n][2], extra u16[nExtra][3] (vertex,u,v), fix u32[nFix][2] (corner,extra)', 'flipY': True,
      'src': 'CC0: skin/hair UVs from the MakeHuman base mesh (LICENSE.ASSETS.md); eye UVs generated'}
hj = json.dumps(hd, separators=(',', ':')).encode()
while (8 + len(hj)) % 4: hj += b' '
out = bytearray(b'YDUV') + struct.pack('<I', len(hj)) + hj + UV.tobytes() + E.tobytes()
while len(out) % 4: out += b'\0'
out += X.tobytes()
open(f'{A}/skin_uv.b64.txt', 'w').write(base64.b64encode(bytes(out)).decode())
print('skin_uv.b64.txt', len(out), 'bytes raw', len(base64.b64encode(bytes(out))), 'b64; extra', len(E), 'fix', len(X))

# Join check: rebuild every corner's UV from the file the way a loader would and compare
rb = np.frombuffer(bytes(out), np.uint16, n * 2, 8 + len(hj)).reshape(n, 2)
fixd = {int(cn): int(e) for cn, e in X}
err = max(np.abs((np.array(E[fixd[cn], 1:]) if cn in fixd else rb[idx[cn]]) / Q - np.clip(uv, 0, 1)).max() for cn, uv in cornerUV.items())
print('max corner UV error', err, '(quantisation', .5 / Q, ')')

if PROOF:
    from PIL import Image, ImageDraw
    J = {k: np.array(v) for k, v in H['joints'].items()}
    def region(c):
        """Body region of a 3D point (packed normal build, metres), for the proof colours."""
        hd_ = J['head']; eyes = [J['eyeL'], J['eyeR']]; mid = (eyes[0] + eyes[1]) / 2
        if min(np.linalg.norm(c - e) for e in eyes) < .022: return (40, 120, 255)                     # eyes and lids: blue
        if abs(c[0]) < .028 and -.075 < c[1] - mid[1] < -.05 and c[2] > mid[2] - .01: return (230, 30, 60)   # lips: red
        if abs(c[0]) < .018 and -.05 < c[1] - mid[1] < -.012 and c[2] > mid[2] + .005: return (255, 160, 0)  # nose: orange
        if abs(c[0]) > .062 and c[1] > hd_[1] - .02 and abs(c[1] - mid[1]) < .045 and c[2] < mid[2] - .03: return (40, 200, 80)  # ears: green
        if c[1] > J['neck'][1]: return (205, 185, 170)                                                    # rest of the head
        if abs(c[0]) > abs(J['handL'][0]) - .02: return (150, 120, 200)                                   # hands: purple
        return (120, 120, 120)
    for name in GROUPS:
        S = 1024; im = Image.new('RGB', (S, S), (255, 255, 255)); dr = ImageDraw.Draw(im)
        s, c = grp[name]; box = []
        for t0 in range(s, s + c, 3):
            uv = [cornerUV[t0 + a] for a in range(3)]; pts = [(u * S, (1 - v) * S) for u, v in uv]
            dr.polygon(pts, fill=region(P[idx[t0:t0 + 3]].mean(0)), outline=(0, 0, 0))
        im.save(f'{PROOF}/uv_{name}.png')
